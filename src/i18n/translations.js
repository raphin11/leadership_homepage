/**
 * 템플릿 문자열 치환 도우미
 * e.g. format('문제 {round} 투표', { round: 1 }) -> '문제 1 투표'
 */
export function format(template, params = {}) {
  if (!template) return '';
  return Object.entries(params).reduce((acc, [k, v]) => {
    return acc.replaceAll(`{${k}}`, String(v));
  }, template);
}
